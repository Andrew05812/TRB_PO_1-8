<?php
// Общие настройки. В реальном проекте значения вроде секретов лучше брать
// из переменных окружения, а не хардкодить в файле - здесь для учебного
// проекта оставлено просто и явно.

declare(strict_types=1);

// SQLite хранит время в UTC, PHP считает timestamp в UTC - фиксируем
// это явно, чтобы окно блокировки не зависело от часового пояса машины.
date_default_timezone_set('UTC');

define('DB_FILE', __DIR__ . '/../data/p5.db');
define('SCHEMA_FILE', __DIR__ . '/../schema.sql');

// Сколько неудачных попыток входа допускаем за окно времени,
// прежде чем временно заблокировать логин/IP (CWE-307 - защита от перебора)
define('MAX_FAILED_ATTEMPTS', 5);
define('LOCKOUT_WINDOW_SECONDS', 15 * 60); // 15 минут

// Небольшая задержка на каждую попытку входа - удорожает автоматический
// перебор ещё до того, как сработает жёсткая блокировка
define('LOGIN_THROTTLE_SECONDS', 1);

// bcrypt (PASSWORD_DEFAULT в PHP 8) использует только первые 72 байта
// пароля. Если этого не ограничить, два разных длинных пароля с одинаковым
// началом будут считаться одним и тем же - поэтому длиннее не принимаем.
define('MAX_PASSWORD_BYTES', 72);
define('MIN_PASSWORD_LENGTH', 8);
define('USERNAME_MAX_LENGTH', 50);

// Хэш-заглушка для несуществующего логина. Нужен, чтобы время ответа
// не выдавало, есть такой пользователь или нет: password_verify() всё
// равно выполняется, просто заведомо с неправильным паролем.
// Это bcrypt cost=10 от случайной строки, сгенерированной один раз.
define('DUMMY_PASSWORD_HASH', '$2y$10$kFhqwwFFx7MMyuZuM5EeKuQ9p/YWLehhsnAO4uZzYlY5S3B5qMLeS');

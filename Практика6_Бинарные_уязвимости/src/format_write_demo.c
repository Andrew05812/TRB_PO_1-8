/*
 * Маленький стенд, на котором удобно показать запись через %n.
 *
 * Строка формата читается в стековый буфер, как это часто бывает в
 * реальных программах (scanf/fgets). Адрес target лежит первыми четырьмя
 * байтами этой строки, поэтому его можно подставить в %n.
 *
 * Цель - глобальная переменная target: её адрес фиксирован, потому что
 * бинарник собран с -no-pie. Так пример не зависит от версии libc.
 */

#include <stdio.h>

int target = 0x41414141;

int main(void)
{
    char buf[128];

    if (fgets(buf, sizeof(buf), stdin) == NULL) {
        return 2;
    }

    printf(buf);
    printf("\ntarget = 0x%08x\n", (unsigned)target);
    return 0;
}
